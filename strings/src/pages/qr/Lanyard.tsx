import styles from './QrModal.module.css'

/* Ленточки лэньярда над бейджем: две белые полоски, уходящие вверх за экран,
 * с надписью «Создаем Нити» вдоль ленты и разделителем-«нитью с узлом»
 * (перекликается с ThreadsNetwork на экране приветствия).
 *
 * Вся геометрия — в единицах макета u (см. --u в QrModal.module.css): viewBox
 * совпадает с размером ленты 41u × 220u, поэтому 1 единица SVG = 1u и надпись
 * масштабируется вместе с лентой. Текст рисуем явными повторами <g>, а не
 * <pattern>: WebKit растеризует паттерны с текстом, и на ретине буквы мылятся. */

const STRAP_W = 41
const STRAP_H = 220

const PHRASE = 'Создаем Нити'
const FONT_SIZE = 12
/* Фиксированная длина надписи (textLength): шаг повторов не зависит от того,
 * какой шрифт подхватился — Inter или системный (в приложении Inter не грузится,
 * на iOS это SF Pro). Разница в ширине глифов уходит в межбуквенный интервал. */
const PHRASE_LEN = 94
/* Оптический центр строчных: базовая линия чуть ниже оси ленты. */
const BASELINE_SHIFT = FONT_SIZE * 0.32
const GAP = 10
const THREAD_LEN = 14
const KNOT_R = 2
/* Тонкая кромка по краям ленты (#c4b5fd — светлый бренд-фиолетовый): читается
 * как тканая окантовка и отделяет белую ленту от светлого верха бейджа. */
const EDGE_INSET = 3.5
const EDGE_WIDTH = 0.8
const STEP = PHRASE_LEN + GAP * 2 + THREAD_LEN

/* Начало первого повтора по длине ленты (в u от её верха). У обеих лент теперь
 * общий top и общая длина, поэтому окно видимости одно и то же: сверху лента
 * уходит за экран (срез плавает по устройствам — 83 - 30/u ≈ 45…59u, см.
 * комментарий у .lanyardLeft в QrModal.module.css), снизу у правой ленты
 * последние 4u закрывает пилюля прорези (у левой низ обрезан раньше, см. ниже).
 * Итого читаемый участок — примерно 45…59u … 216u.
 *
 * Шаг повтора STEP = 128u: фраза 94u, промежуток 10u, нить с узлом 14u,
 * промежуток 10u. Отсчёт идёт вверх от точки PHASE (текст читается снизу
 * вверх), то есть для повтора с началом Y: фраза Y-94…Y, нить Y-118…Y-104.
 *
 * Правая (передняя) лента, фаза 182 — повторы садятся на 54 / 182 / 310u:
 *   54…64 промежуток, 64…78 нить с узлом, 78…88 промежуток,
 *   88…182 ФРАЗА ЦЕЛИКОМ, 182…192 промежуток, 192…206 нить с узлом,
 *   206…216 промежуток и сразу прорезь.
 * Нижний срез (пилюля на 216u) приходится ровно на конец фразы — ни одна буква
 * не режется. Верхний срез плавает по устройствам и в промежуток 54…64u попадает
 * не везде: на 390×844, 430×932 и планшете — да, на 375×812 у верхней кромки
 * экрана торчит 1u первой буквы, на 375×667 и 360×640 — до 9u. Свести оба среза
 * на промежуток одной фазой нельзя: между ними 133 + 30/u, по модулю STEP это
 * 29…43u в зависимости от устройства, а промежуток+нить+промежуток дают всего
 * 34u. Выбран чистый нижний срез — верхний и так уходит под чёлку/статус-бар.
 *
 * Левая (дальняя) лента продета ЗА карточку (z-index -1), поэтому её низ режут
 * два края сразу: кромка карточки на py≈203u (220 − 4u захода − 13u утопления
 * прорези) и, выше неё, правая лента — но та скрывает НЕ всё сразу: «нить» и
 * узел уходят под неё с py≈186u и 189u, а буквы — только с py≈195u (чернила
 * текста ближе к оси ленты, чем её край). Строже именно 195u.
 * Фаза левой оставлена прежней (179): видимый кусок — нить на 61…75u и фраза
 * целиком на 85…179u, а хвост следующей фразы (213…216u, последние 3u последней
 * буквы) держится ровно на том, что 213 > 195 (и заодно > 203 — он и так за
 * карточкой). Если двигать эту фазу — ориентируйся на 195u, иначе буква вылезет
 * из-под правой ленты на 186…195u. */
const PHASE: Record<Side, number> = { left: 179, right: 182 }
const REPEATS = [-1, 0, 1]

type Side = 'left' | 'right'

/* Один повтор в координатах «вдоль ленты»: x — по длине, y — поперёк, 0 — ось. */
const Repeat = () => (
  <>
    <text
      x={0}
      y={BASELINE_SHIFT}
      fontSize={FONT_SIZE}
      fontWeight={600}
      textLength={PHRASE_LEN}
      lengthAdjust="spacing"
      fill="currentColor"
    >
      {PHRASE}
    </text>
    <line
      x1={PHRASE_LEN + GAP}
      x2={PHRASE_LEN + GAP + THREAD_LEN}
      y1={0}
      y2={0}
      stroke="currentColor"
      strokeWidth={1}
      strokeLinecap="round"
    />
    <circle cx={PHRASE_LEN + GAP + THREAD_LEN / 2} cy={0} r={KNOT_R} fill="currentColor" />
  </>
)

/* Обе ленты читаются снизу вверх — одна непрерывная печать по шнурку, который
 * уходит за шею и возвращается: буквы на левой и правой ленте повёрнуты
 * одинаково, rotate(-90). Поэтому на левой ленте верх букв смотрит наружу, а на
 * правой — внутрь, к центру бейджа (так на макете).
 * Знак у смещения повторов не нужен: REPEATS симметричен, и набор
 * {PHASE-STEP, PHASE, PHASE+STEP} от направления не зависит. */
const Strap = ({ side }: { side: Side }) => (
  <svg
    className={styles.lanyardPrint}
    viewBox={`0 0 ${STRAP_W} ${STRAP_H}`}
    preserveAspectRatio="none"
    aria-hidden="true"
    focusable="false"
  >
    <g className={styles.lanyardEdge} strokeWidth={EDGE_WIDTH}>
      <line x1={EDGE_INSET} x2={EDGE_INSET} y1={0} y2={STRAP_H} />
      <line x1={STRAP_W - EDGE_INSET} x2={STRAP_W - EDGE_INSET} y1={0} y2={STRAP_H} />
    </g>
    {REPEATS.map((i) => (
      <g key={i} transform={`translate(${STRAP_W / 2} ${PHASE[side] + i * STEP}) rotate(-90)`}>
        <Repeat />
      </g>
    ))}
  </svg>
)

/** Декоративные ленточки бейджа. Позиционируются абсолютно внутри .modal / .content. */
export const Lanyard = () => (
  <>
    <div className={styles.lanyardLeft} aria-hidden="true">
      <Strap side="left" />
    </div>
    <div className={styles.lanyardRight} aria-hidden="true">
      <Strap side="right" />
    </div>
  </>
)
