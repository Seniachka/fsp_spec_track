export const searchUniversities = (query: string, catalog?: University[]): University[] => {
  const list = catalog ?? getUniversitiesCatalog()
  const q = query.trim().toLowerCase()
  if (!q) return list
  return list.filter(
    (item) => item.name.toLowerCase().includes(q) || item.shortName.toLowerCase().includes(q),
  )
}

let universitiesCache: University[] | null = null

export const setUniversitiesCache = (list: University[]): void => {
  universitiesCache = list.length > 0 ? list : null
}

/**
 * Дописать в кэш вузы, найденные серверным поиском, не выбрасывая уже известные.
 * Поиск отдаёт одну страницу справочника, а getUniversityById должен продолжать
 * находить вузы из прошлых страниц и из локального каталога — поэтому именно
 * merge, а не setUniversitiesCache.
 */
export const mergeUniversitiesCache = (list: University[]): void => {
  if (list.length === 0) return
  const byId = new Map(getUniversitiesCatalog().map((item) => [item.id, item]))
  list.forEach((item) => byId.set(item.id, item))
  universitiesCache = Array.from(byId.values())
}

export const getUniversitiesCatalog = (): University[] => universitiesCache ?? UNIVERSITIES

export const getUniversityById = (id: number): University | undefined =>
  getUniversitiesCatalog().find((item) => item.id === id)

