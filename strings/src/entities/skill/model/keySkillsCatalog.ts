export const searchKeySkills = (query: string): KeySkillCatalogItem[] => {
  const q = query.trim().toLowerCase()
  if (!q) return KEY_SKILLS_CATALOG
  return KEY_SKILLS_CATALOG.filter((item) => item.name.toLowerCase().includes(q))
}

export const getKeySkillById = (id: number): KeySkillCatalogItem | undefined =>
  KEY_SKILLS_CATALOG.find((item) => item.id === id)
