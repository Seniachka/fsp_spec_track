def _mcq(code, spec, grades, stratum, difficulty, topic, prompt, options, correct, anchor=False):
    letters = ["a", "b", "c", "d"]
    return {
        "code": code,
        "spec": spec,
        "grades": grades,
        "stratum": stratum,
        "difficulty": difficulty,
        "kind": "mcq",
        "anchor": anchor,
        "topic": topic,
        "prompt": prompt,
        "payload": {
            "options": [{"id": letters[i], "text": text} for i, text in enumerate(options)],
            "correct": correct,
        },
    }


def _code(code, spec, grades, difficulty, topic, prompt, signature, starter, language, variants):
    return {
        "code": code,
        "spec": spec,
        "grades": grades,
        "stratum": "target",
        "difficulty": difficulty,
        "kind": "code",
        "anchor": False,
        "topic": topic,
        "prompt": prompt,
        "payload": {
            "language": language,
            "signature": signature,
            "starter": starter,
            "variants": variants,
        },
    }


def _py(public_args, public_expected, hidden):
    return {"public": {"args": public_args, "expected": public_expected}, "hidden": hidden}


